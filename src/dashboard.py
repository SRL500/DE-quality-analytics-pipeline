"""
It reads the clean tables from data/pipeline.duckdb and the CSV reports from reports/.
Run the pipeline (python src/run_pipeline.py) at least once before starting it.
Tip: stop the pipeline before opening the dashboard (DuckDB allows one writer at a time).
"""
from pathlib import Path

import duckdb
import pandas as pd
import streamlit as st

ROOT = Path(__file__).resolve().parents[1]
DB_PATH = ROOT / "data" / "pipeline.duckdb"
REPORTS = ROOT / "reports"

st.set_page_config(page_title="E-Commerce Data Quality & Analytics", page_icon="📊", layout="wide")


def query(sql):
    """Run a read-only SQL query on the DuckDB file and return a DataFrame."""
    con = duckdb.connect(str(DB_PATH), read_only=True)
    try:
        return con.execute(sql).df()
    finally:
        con.close()


@st.cache_data
def load_orders():
    df = query("""
        SELECT o.order_id, o.order_date, o.status, o.payment_method, o.quantity, o.revenue,
               o.customer_id, p.product_name, p.category, c.city
        FROM clean.orders o
        JOIN clean.products  p ON o.product_id  = p.product_id
        JOIN clean.customers c ON o.customer_id = c.customer_id
    """)
    df["order_date"] = pd.to_datetime(df["order_date"])
    return df


@st.cache_data
def load_rejected():
    return query("SELECT reject_reason, COUNT(*) AS n_rows FROM clean.rejected_orders "
                 "GROUP BY 1 ORDER BY 2 DESC")


@st.cache_data
def load_csv(name):
    return pd.read_csv(REPORTS / name)


# ------------------------------------------------------------------ header
st.title("📊 E-Commerce Data Quality & Analytics Dashboard")
st.caption("Python + DuckDB | ISE 2 Practical Case Study #19 | synthetic dataset generated by our own script")

try:
    orders = load_orders()
except Exception as e:  # pipeline not run yet / DB locked
    st.error(f"Could not read the DuckDB file. Run `python src/run_pipeline.py` first. Details: {e}")
    st.stop()

# ----------------------------------------------------------------- sidebar
with st.sidebar:
    st.header("Filters (Sales tab)")
    all_cats = sorted(orders["category"].unique())
    all_cities = sorted(orders["city"].unique())
    cats = st.multiselect("Category", all_cats, default=all_cats)
    cities = st.multiselect("City", all_cities, default=all_cities)
    dmin, dmax = orders["order_date"].min().date(), orders["order_date"].max().date()
    dr = st.date_input("Order date range", (dmin, dmax), min_value=dmin, max_value=dmax)
    net_only = st.checkbox("Count only delivered + shipped orders", value=True)

start, end = (dr[0], dr[1]) if isinstance(dr, tuple) and len(dr) == 2 else (dmin, dmax)
f = orders[orders["category"].isin(cats) & orders["city"].isin(cities)
           & (orders["order_date"].dt.date >= start) & (orders["order_date"].dt.date <= end)]
if net_only:
    f = f[f["status"].isin(["delivered", "shipped"])]

tab_q, tab_s, tab_r, tab_p = st.tabs(["✅ Data Quality", "📈 Sales Analytics", "🗂️ Rejected Rows", "⚡ Performance"])

# ------------------------------------------------------------ data quality
with tab_q:
    raw, cln = load_csv("quality_raw.csv"), load_csv("quality_clean.csv")
    c1, c2, c3 = st.columns(3)
    c1.metric("Raw quality score", f"{raw['pass_rate_pct'].mean():.2f}%")
    c2.metric("Clean quality score", f"{cln['pass_rate_pct'].mean():.2f}%",
              f"{cln['pass_rate_pct'].mean() - raw['pass_rate_pct'].mean():+.2f} pts")
    c3.metric("Rules checked", len(raw))

    q = raw.merge(cln, on=["table", "rule", "dimension"], suffixes=("_raw", "_clean"))
    dims = ["All"] + sorted(q["dimension"].unique())
    pick = st.selectbox("Filter by quality dimension", dims)
    if pick != "All":
        q = q[q["dimension"] == pick]
    q["rule_name"] = q["table"] + "." + q["rule"]
    st.bar_chart(q.set_index("rule_name")[["pass_rate_pct_raw", "pass_rate_pct_clean"]])
    st.dataframe(q[["table", "rule", "dimension", "failed_rows_raw", "failed_rows_clean",
                    "pass_rate_pct_raw", "pass_rate_pct_clean"]], use_container_width=True)

# ------------------------------------------------------------------- sales
with tab_s:
    if f.empty:
        st.warning("No orders match the current filters.")
    else:
        k1, k2, k3, k4 = st.columns(4)
        k1.metric("Revenue", f"{f['revenue'].sum():,.0f}")
        k2.metric("Orders", f"{len(f):,}")
        k3.metric("Customers", f"{f['customer_id'].nunique():,}")
        k4.metric("Avg order value", f"{f['revenue'].mean():,.0f}")

        st.subheader("Monthly revenue")
        monthly = f.groupby(f["order_date"].dt.to_period("M").astype(str))["revenue"].sum()
        st.line_chart(monthly)

        a, b = st.columns(2)
        with a:
            st.subheader("Revenue by category")
            st.bar_chart(f.groupby("category")["revenue"].sum().sort_values(ascending=False))
            st.subheader("Payment mix (orders)")
            st.bar_chart(f["payment_method"].value_counts())
        with b:
            st.subheader("Revenue by city")
            st.bar_chart(f.groupby("city")["revenue"].sum().sort_values(ascending=False))
            st.subheader("Top 10 products")
            st.dataframe(f.groupby(["product_name", "category"], as_index=False)
                          .agg(units=("quantity", "sum"), revenue=("revenue", "sum"))
                          .sort_values("revenue", ascending=False).head(10),
                         use_container_width=True)

# ---------------------------------------------------------------- rejected
with tab_r:
    rej = load_rejected()
    st.metric("Total rejected orders", f"{int(rej['n_rows'].sum()):,}")
    st.bar_chart(rej.set_index("reject_reason"))
    st.caption("Every rejected row is kept in clean.rejected_orders with its reason (audit trail).")
    reason = st.selectbox("Inspect a reason", rej["reject_reason"].tolist())
    st.dataframe(query(f"SELECT * FROM clean.rejected_orders WHERE reject_reason = '{reason}' LIMIT 200"),
                 use_container_width=True)

# ------------------------------------------------------------- performance
with tab_p:
    try:
        bench = load_csv("benchmark.csv")
        sizes = load_csv("benchmark_sizes.csv").iloc[0]
        s1, s2, s3 = st.columns(3)
        s1.metric("Benchmark rows", f"{int(sizes['rows']):,}")
        s2.metric("CSV size", f"{sizes['csv_mb']} MB")
        s3.metric("Parquet size", f"{sizes['parquet_mb']} MB",
                  f"{sizes['csv_mb'] / sizes['parquet_mb']:.1f}x smaller", delta_color="off")
        st.bar_chart(bench.pivot(index="query", columns="format", values="median_sec"))
        st.caption("Median query time in seconds (lower is better).")
    except FileNotFoundError:
        st.warning("Run the benchmark step first (python src/benchmark.py).")